// Writes supabase/seed.sql: the curated catalogue from js/store.js as plain SQL (same rules as seed.ts:
// stock split evenly across sizes, no invented ratings/sold counts, no staff accounts, no browser orders).
// Usage: cd server && npx tsx src/db/seed-sql.ts > ../supabase/seed.sql
import { loadLegacySeed, SHOPS, skuFor, splitStock } from './legacy-catalog.js';

const q = (v: unknown) => v === null || v === undefined ? 'NULL' : "'" + String(v).replace(/'/g, "''") + "'";
const j = (v: unknown) => q(JSON.stringify(v)) + '::jsonb';
const cents = (rs: number) => Math.round(Number(rs) * 100);
const HEX = /^#[0-9a-f]{3,8}$/i;
const d = loadLegacySeed();
const s = d.settings;
const out: string[] = [];
const w = (x: string) => out.push(x);

w('-- Generated by server/src/db/seed-sql.ts from js/store.js. Do not edit by hand.');
w('-- Seeds an EMPTY database only (the guard below stops it if products already exist).');
w('SET search_path = app, extensions;');
w("DO $$ BEGIN IF EXISTS (SELECT 1 FROM app.products) THEN RAISE EXCEPTION 'catalogue already present: seed refused'; END IF; END $$;");
for (const [i, o] of (s.origins as any[]).entries())
  w(`INSERT INTO import_countries (code, name, iso2, label, days, enabled, sort_order) VALUES (${q(o.id)}, ${q(o.name)}, ${q(o.code)}, ${q(o.label)}, ${q(o.days)}, ${o.on !== false}, ${i + 1}) ON CONFLICT (code) DO NOTHING;`);
w(`UPDATE import_countries SET days = ${q(s.localDays || '2–4')} WHERE code = 'local';`);
const catShop = new Map<string, string>();
for (const [i, sh] of SHOPS.entries()) {
  w(`INSERT INTO shops (slug, name, sort_order) VALUES (${q(sh.slug)}, ${q(sh.name)}, ${i});`);
  sh.categories.forEach(c => catShop.set(c, sh.slug));
}
for (const [i, c] of (d.categories as any[]).entries())
  w(`INSERT INTO categories (slug, shop_id, name, tagline, shape, icon_color, sort_order) SELECT ${q(c.id)}, id, ${q(c.name)}, ${q(c.tagline || '')}, ${q(c.shape || 'tshirt')}, ${q(HEX.test(c.icon) ? c.icon : '#0b2a6f')}, ${i} FROM shops WHERE slug = ${q(catShop.get(c.id) || 'clothing')};`);
for (const [i, c] of (d.collections as any[]).entries())
  w(`INSERT INTO collections (slug, name, description, accent, home_row, sort_order) VALUES (${q(c.id)}, ${q(c.name)}, ${q(c.description || '')}, ${q(HEX.test(c.accent) ? c.accent : '#0b2a6f')}, ${!!c.homeRow}, ${i});`);
let variants = 0, units = 0;
for (const p of d.products as any[]) {
  w(`INSERT INTO products (slug, shop_id, category_id, name, brand, description, origin_code, badge, featured, flash, price_cents, compare_price_cents, visual, created_at)
  SELECT ${q(p.id)}, c.shop_id, c.id, ${q(p.name)}, ${q(p.brand || '')}, ${q(p.description || '')}, ${q(p.origin)}, ${q(p.badge || '')}, ${!!p.featured}, ${!!p.flash}, ${cents(p.price)}, ${cents(p.comparePrice || 0)}, ${j({ shape: p.shape, pattern: p.pattern, color: p.color, accent: p.accent })}, to_timestamp(${Number(p.createdAt || 0)} / 1000.0) FROM categories c WHERE c.slug = ${q(p.category)};`);
  const sizes: string[] = p.sizes && p.sizes.length ? p.sizes : [''];
  const stock = splitStock(Number(p.stock) || 0, sizes.length);
  for (const [i, size] of sizes.entries()) {
    const sku = skuFor(p.id, size);
    w(`INSERT INTO product_variants (product_id, sku, size, sort_order) SELECT id, ${q(sku)}, ${q(size)}, ${i} FROM products WHERE slug = ${q(p.id)};`);
    w(`INSERT INTO inventory (variant_id, on_hand) SELECT id, ${stock[i]} FROM product_variants WHERE sku = ${q(sku)};`);
    if (stock[i]) w(`INSERT INTO inventory_movements (variant_id, delta_on_hand, reason, note) SELECT id, ${stock[i]}, 'seed', 'initial catalogue' FROM product_variants WHERE sku = ${q(sku)};`);
    variants++; units += stock[i];
  }
  for (const [i, col] of (p.collections || []).entries())
    w(`INSERT INTO collection_products (collection_id, product_id, sort_order) SELECT co.id, p.id, ${i} FROM collections co, products p WHERE co.slug = ${q(col)} AND p.slug = ${q(p.id)};`);
}
for (const [i, h] of (d.hero as any[]).entries())
  w(`INSERT INTO banners (public_id, sort_order, eyebrow, title, subtitle, cta, link, color, shape) VALUES (${q(h.id)}, ${i}, ${q(h.eyebrow || '')}, ${q(h.title || '')}, ${q(h.subtitle || '')}, ${q(h.cta || '')}, ${q(h.link || '#')}, ${q(HEX.test(h.color) ? h.color : '#0b2a6f')}, ${q(h.shape || 'tshirt')});`);
w(`UPDATE globe_settings SET cities = ARRAY[${(s.globeCities as string[]).map(q).join(', ')}]::text[], stats = ${j(s.globeStats)}, steps = ${j(s.globeSteps)}, hero_title = ${q(s.heroTitle)}, hero_subtitle = ${q(s.heroSubtitle)} WHERE id = 1;`);
w(`UPDATE flash_sale_rules SET title = ${q(s.flashTitle || 'Flash Sale')}, mode = ${q(s.flashMode === 'until' ? 'daily' : (s.flashMode || 'daily'))} WHERE id = 1;`);
w(`UPDATE shipping_rates SET fee_cents = ${cents(s.shippingFee)}, free_over_cents = ${s.freeShipping ? cents(s.freeShipping) : 'NULL'} WHERE code = 'standard';`);
w(`UPDATE payment_settings SET instructions = ${q(s.bankDetails || '')} WHERE method = 'bank_transfer';`);
const content = { brand: s.brand, announcement: s.announcement, currency: 'Rs.', phone: s.phone, email: s.email, address: s.address, whatsapp: s.whatsapp,
  chinaDays: s.chinaDays, returnDays: s.returnDays, welcome: s.welcome, navLinks: s.navLinks, sections: s.sections, services: s.services,
  sellerStats: [], chinaSteps: s.chinaSteps, faq: s.faq };
w(`INSERT INTO site_content (key, value) VALUES ('storefront', ${j(content)});`);
w(`-- totals: ${d.products.length} products, ${variants} variants, ${units} stock units`);
process.stdout.write(out.join('\n') + '\n');
